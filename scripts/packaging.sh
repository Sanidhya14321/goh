#!/bin/sh
# Writes the Homebrew formula (dist/goh.rb) and the Scoop manifest
# (dist/goh.json) for VERSION from dist/SHA256SUMS. The release workflow
# attaches both to the release and, for stable versions, commits them to
# Formula/ and bucket/ so `brew tap` and `scoop bucket add` work from this
# repository.
#
# Usage: scripts/packaging.sh VERSION [DIST] [BASE_URL]
set -eu
version=${1:?usage: scripts/packaging.sh VERSION [DIST] [BASE_URL]}
dist=${2:-dist}
base=${3:-https://github.com/Sanidhya14321/goh/releases/download/v$version}
sums="$dist/SHA256SUMS"
test -s "$sums" || { echo "missing $sums" >&2; exit 1; }

sum() {
    value=$(awk -v f="$1" '$2 == f || $2 == "*" f {print $1}' "$sums")
    test -n "$value" || { echo "no checksum for $1 in $sums" >&2; exit 1; }
    printf '%s' "$value"
}

cat > "$dist/goh.rb" <<EOF
# Generated by scripts/packaging.sh for goh $version; do not edit.
class Goh < Formula
  desc "Terminal coding assistant with tools, sessions, MCP and LSP"
  homepage "https://github.com/Sanidhya14321/goh"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/goh-darwin-arm64"
      sha256 "$(sum goh-darwin-arm64)"
    end
    on_intel do
      url "$base/goh-darwin-amd64"
      sha256 "$(sum goh-darwin-amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$base/goh-linux-arm64"
      sha256 "$(sum goh-linux-arm64)"
    end
    on_intel do
      url "$base/goh-linux-amd64"
      sha256 "$(sum goh-linux-amd64)"
    end
  end

  def install
    bin.install Dir["goh-*"].first => "goh"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/goh version").strip
  end
end
EOF

cat > "$dist/goh.json" <<EOF
{
    "version": "$version",
    "description": "Terminal coding assistant with tools, sessions, MCP and LSP",
    "homepage": "https://github.com/Sanidhya14321/goh",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$base/goh-windows-amd64.exe#/goh.exe",
            "hash": "$(sum goh-windows-amd64.exe)"
        },
        "arm64": {
            "url": "$base/goh-windows-arm64.exe#/goh.exe",
            "hash": "$(sum goh-windows-arm64.exe)"
        }
    },
    "bin": "goh.exe",
    "checkver": {
        "github": "https://github.com/Sanidhya14321/goh"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/Sanidhya14321/goh/releases/download/v\$version/goh-windows-amd64.exe#/goh.exe"
            },
            "arm64": {
                "url": "https://github.com/Sanidhya14321/goh/releases/download/v\$version/goh-windows-arm64.exe#/goh.exe"
            }
        },
        "hash": {
            "url": "https://github.com/Sanidhya14321/goh/releases/download/v\$version/SHA256SUMS"
        }
    }
}
EOF
echo "wrote $dist/goh.rb and $dist/goh.json for $version"
