func TestGeneratedFileProtectionAtPreviewAndExecution(t *testing.T) {
	e, root := engine(t)
	const source = "\xef\xbb\xbf/* License */\r\n// Code generated by fixture. DO NOT EDIT.\r\npackage fixture\r\n"
	path := filepath.Join(root, "source.go")
	if err := os.WriteFile(path, []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	for name, args := range map[string]map[string]any{
		"edit_file":  {"old_text": "package fixture", "new_text": "package updated"},
		"write_file": {"content": "package updated\n"},
	} {
		args["path"], args["expected_sha256"] = "source.go", hash([]byte(source))
		raw := mustJSON(t, args)
		if _, _, err := e.Prepare(name, raw); err == nil || !strings.Contains(err.Error(), "generated-file header") {
			t.Fatalf("%s preparation accepted a generated file: %v", name, err)
		}
		if got := e.Execute(context.Background(), name, raw); !got.Error || !strings.Contains(got.Content, "generated-file header") {
			t.Fatalf("%s execution accepted a generated file: %+v", name, got)
		}
	}
	if bytes, err := os.ReadFile(path); err != nil || string(bytes) != source {
		t.Fatalf("protected file changed: %q, %v", bytes, err)
	}

	e.AllowGeneratedEdits = true
	raw := mustJSON(t, map[string]any{
		"path": "source.go", "content": "package updated\n", "expected_sha256": hash([]byte(source)),
	})
	if got := e.Execute(context.Background(), "write_file", raw); got.Error {
		t.Fatal(got)
	}
}

func TestGeneratedPatchSourceBlocksWholePatch(t *testing.T) {
	e, root := engine(t)
	const body = "/* @generated */\nconst value = 1;\n"
	if err := os.WriteFile(filepath.Join(root, "source.ts"), []byte(body), 0600); err != nil {
		t.Fatal(err)
	}
	for _, operation := range [][]string{
		{"*** Delete File: source.ts"},
		{"*** Update File: source.ts", "*** Move to: moved.ts", "@@", "-const value = 1;", "+const value = 2;"},
	} {
		lines := append([]string{"*** Add File: unrelated", "+new"}, operation...)
		raw := patchInput(t, patchText(lines...), map[string]string{"source.ts": hash([]byte(body))})
		if got := e.Execute(context.Background(), "apply_patch", raw); !got.Error || !strings.Contains(got.Content, "generated-file header") {
			t.Fatal(got)
		}
		for _, name := range []string{"unrelated", "moved.ts"} {
			if _, err := os.Stat(filepath.Join(root, name)); !os.IsNotExist(err) {
				t.Fatalf("patch published %s: %v", name, err)
			}
		}
	}
}

func TestGeneratedMarkerAfterCodeDoesNotBlockEdit(t *testing.T) {
	e, root := engine(t)
	const source = "package example\n// Code generated by fixture. DO NOT EDIT.\n"
	if err := os.WriteFile(filepath.Join(root, "example.go"), []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	raw := mustJSON(t, map[string]any{
		"path": "example.go", "old_text": "package example", "new_text": "package updated",
		"expected_sha256": hash([]byte(source)),
	})
	if got := e.Execute(context.Background(), "edit_file", raw); got.Error {
		t.Fatal(got)
	}
}
